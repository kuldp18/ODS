package org.ods.scanner

/** Standalone checks using the installed Kotlin compiler; no Android SDK or Gradle cache needed. */
fun main() {
    check(Crop.Full.valid())
    check(Crop.Full.area() == 1f)
    check(Crop.decode(Crop.Full.encode()) == Crop.Full)
    check(!Crop(listOf(Corner(0f, 0f), Corner(1f, 1f), Corner(1f, 0f), Corner(0f, 1f))).valid())
    check(!Crop(listOf(Corner(0f, 0f), Corner(1f, 0f), Corner(.1f, .1f), Corner(0f, 1f))).valid())
    check(!Crop(List(4) { Corner(.5f, .5f) }).valid())
    check(Crop.decode("NaN,0;1,0;1,1;0,1") == Crop.Full)
    check(safeName("../../invoice") == "_.._invoice")
    check(safeName("हिंदी invoice") == "हिंदी invoice")
    check(safeName("...") == "Document")
    check(safeName("x".repeat(200)).length == 80)
    val inset = Crop(listOf(Corner(.1f,.1f), Corner(.9f,.1f), Corner(.9f,.9f), Corner(.1f,.9f)))
    check(inset.handles().size == 8)
    val edge = inset.move(4, 0f, .1f)
    check(edge.points[0].y == .2f && edge.points[1].y == .2f)
    check(edge.points[2] == inset.points[2] && edge.points[3] == inset.points[3])
    check(inset.move(4, 0f, -10f).points.take(2).all { it.y == 0f })
    check(inset.move(0, 1f, 1f) == inset)
    check(inset.move(0, Float.NaN, 0f) == inset)
    val gate = AutoCaptureGate()
    check(!gate.update(inset, true, 0))
    check(!gate.update(inset, true, 599))
    check(gate.update(inset, true, 600))
    check(!gate.update(inset, true, 2000))
    check(!gate.update(null, true, 2001))
    check(!gate.update(inset, true, 2100))
    check(gate.update(inset, true, 2700))
    println("24 geometry, capture gating and filename checks passed")
}
